/**
 * Normalise the ways a channel is named onto one glyph: LinkedIn's two
 * credential kinds, and the `facebook` channel key onto the Meta mark.
 */
export function glyphProvider(provider: string): string {
  const key = provider.toLowerCase();
  if (key.startsWith("linkedin")) return "linkedin";
  if (key === "facebook") return "meta";
  return key;
}

export function ChannelGlyph({
  provider,
  size = 36,
  className,
}: {
  provider: string;
  size?: number;
  className?: string;
}) {
  const brand = CHANNEL_BRAND[glyphProvider(provider)];
  if (!brand) return null;
  const style: CSSProperties = {
    background: brand.bg,
    width: size,
    height: size,
    borderRadius: Math.max(4, Math.round(size * 0.28)),
  };
  return (
    <span className={cn("grid shrink-0 place-items-center shadow-sm", className)} style={style} aria-hidden>
      <span className="grid place-items-center" style={{ transform: `scale(${size / 36})` }}>
        {brand.icon}
      </span>
    </span>
  );
}
