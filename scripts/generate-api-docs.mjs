#!/usr/bin/env node
/**
 * Regenerate the endpoint reference inside `docs/PUBLIC_API.md`.
 *
 * The document was 500-plus lines of hand-maintained tables covering three
 * surfaces. It is good documentation, and it was one refactor away from being
 * wrong: it described Connect scheduling correctly and never mentioned that
 * the public API silently discarded the same field.
 *
 * The split is deliberate. Everything hand-written stays hand-written, because
 * concepts, auth, the draft-then-publish flow, delivery modes, and worked curl
 * examples are the parts a generator cannot produce and a reader most needs.
 * Only the endpoint list is generated, from the OpenAPI document, which is
 * itself generated from the Zod schemas the routes validate against.
 *
 * The generated region is delimited by HTML comments. Everything between them
 * is replaced; everything outside is never touched.
 *
 * Usage:
 *   node --import ./scripts/lib/ts-alias-loader.mjs scripts/generate-api-docs.mjs
 *   node --import ./scripts/lib/ts-alias-loader.mjs scripts/generate-api-docs.mjs --check
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildOpenApiDocument } from '@/lib/public-api/openapi';
import { listErrorCodes } from '@/lib/error-codes';

const DOC = join(process.cwd(), 'docs', 'PUBLIC_API.md');
const START = '<!-- generated:endpoints:start -->';
const END = '<!-- generated:endpoints:end -->';
const check = process.argv.includes('--check');

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete'];

function renderEndpoints() {
  const doc = buildOpenApiDocument();
  const rows = [];

  for (const [path, methods] of Object.entries(doc.paths)) {
    for (const method of METHOD_ORDER) {
      const operation = methods[method];
      if (!operation) continue;
      const summary = operation.summary || '';
      const params = (operation.parameters || [])
        .filter((parameter) => parameter.in === 'query')
        .map((parameter) => `\`${parameter.name}\``)
        .join(', ');
      rows.push(
        `| \`${method.toUpperCase()} ${path}\` | ${summary} | ${params || 'n/a'} |`,
      );
    }
  }

  const retryable = listErrorCodes().filter((record) => record.retryable);

  return [
    START,
    '',
    '<!-- Generated by scripts/generate-api-docs.mjs from the OpenAPI document.',
    '     Do not edit between these markers; run `npm run docs:api` instead. -->',
    '',
    '### Endpoint reference',
    '',
    `Generated from the [OpenAPI description](/api/public/v1/openapi.json), which is itself generated from the schemas the routes validate against. ${Object.keys(doc.paths).length} paths.`,
    '',
    '| Endpoint | What it does | Query parameters |',
    '| --- | --- | --- |',
    ...rows,
    '',
    '### Retryable errors',
    '',
    'An identical retry can plausibly succeed for these codes and only these. For everything else, change something first.',
    '',
    ...retryable.map((record) => `- \`${record.code}\` (${record.status}): ${record.description}`),
    '',
    `The full catalogue, ${listErrorCodes().length} codes with statuses and meanings, is in the OpenAPI description under **Errors**.`,
    '',
    END,
  ].join('\n');
}

const source = readFileSync(DOC, 'utf8');
const startIndex = source.indexOf(START);
const endIndex = source.indexOf(END);

if (startIndex === -1 || endIndex === -1) {
  console.error(
    `docs/PUBLIC_API.md has no generated region.\n` +
    `Add the markers ${START} and ${END} where the endpoint reference should go.`,
  );
  process.exit(1);
}

const updated =
  source.slice(0, startIndex) + renderEndpoints() + source.slice(endIndex + END.length);

if (!check) {
  writeFileSync(DOC, updated);
  console.log('Regenerated the endpoint reference in docs/PUBLIC_API.md');
  process.exit(0);
}

if (updated !== source) {
  console.error(
    'The endpoint reference in docs/PUBLIC_API.md is out of date.\n' +
    'Run `npm run docs:api` and commit the result.',
  );
  process.exit(1);
}

console.log('docs:api check passed');
